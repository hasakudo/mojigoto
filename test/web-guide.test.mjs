import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("Web簡易ガイドと画面幅別の設定ラベルを表示する", async () => {
  const html = await readFile(new URL("../web/index.html", import.meta.url), "utf8");
  const css = await readFile(new URL("../web/styles.css", import.meta.url), "utf8");
  const app = await readFile(new URL("../web/app.mjs", import.meta.url), "utf8");
  const serviceWorker = await readFile(new URL("../web/sw.js", import.meta.url), "utf8");
  assert.match(html, /id="guideDialog"/);
  assert.match(html, /id="loginGuideContent"/);
  assert.match(html, /id="appGuideContent"/);
  assert.match(html, /もじごとガイド/);
  assert.match(html, /利用申請時に登録したメールアドレス/);
  assert.match(html, /OneDriveまたはGoogle Drive/);
  assert.match(html, /前回開いていた一覧や編集画面/);
  assert.match(html, /原稿を編集したままプロット・資料を選んで確認できます/);
  assert.match(html, /選択範囲に付いた括弧・ルビ・傍点の記法を外します/);
  assert.match(html, /Ctrl \+ S/);
  assert.match(html, /Command \+ S/);
  assert.match(html, /Esc/);
  assert.match(html, /Alt \+ 1〜6/);
  assert.match(html, /Option \+ 1〜6/);
  assert.match(app, /conceptMemoEditorSection\.addEventListener\("keydown"/);
  assert.match(app, /noteEditorSection\.addEventListener\("keydown"/);
  assert.match(app, /querySelectorAll\("dialog\[open\]"\)/);
  assert.match(app, /\.multi-filter\[open\], \.count-mode-details\[open\]/);
  assert.match(app, /const WORK_DESTINATION_SHORTCUTS =/);
  assert.match(app, /"6": "settings"/);
  assert.match(html, /同じ作品フォルダを開き/);
  assert.doesNotMatch(html, /片方だけ古い状態では|全体設定をまだ行っていない場合は従来/);
  assert.doesNotMatch(html, /Microsoft アプリIDを保存します/);
  assert.doesNotMatch(html, /アプリIDは管理者が設定しています/);
  assert.doesNotMatch(html, /クライアントシークレットやアカウントのパスワード/);
  assert.doesNotMatch(html, /<summary><span>G<\/span>/);
  assert.match(html, /aria-label="接続設定">接続設定</);
  assert.match(html, /class="nav-label-wide">作品設定</);
  assert.match(html, /class="nav-label-compact">設定</);
  assert.match(css, /\.global-work-nav \.nav-label-wide \{ display: none; \}/);
  assert.match(css, /\.icon-house \{ --icon: url\("data:image\/svg\+xml;base64,/);
  assert.doesNotMatch(serviceWorker, /\.\/icons\/house\.svg/);
  assert.doesNotMatch(html, /接続設定のアプリIDとリダイレクトURI/);
  assert.match(app, /elements\.guideButton\.addEventListener\("click", openGuide\)/);
  assert.match(app, /const openedFromLogin = !elements\.loginGate\.hidden/);
});
